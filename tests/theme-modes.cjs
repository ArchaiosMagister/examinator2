/* Temas en Examinator2: persistencia, blanco/oscuro/OLED y exportaciones intactas. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('index.html'), css=read('styles.css'), sw=read('sw.js'), start=read('js/start.js');
assert.match(html,/<script src="js\/theme\.js"><\/script>/);
assert.ok(html.indexOf('src="js/theme.js"')<html.indexOf('<body>'),'Aplicar el modo visual antes de dibujar el cuerpo');
assert.match(sw,/"\.\/js\/theme\.js"/);
assert.match(start,/<option value="dark">Oscuro<\/option>/);
assert.match(start,/<option value="oled">OLED \(negro puro\)<\/option>/);
assert.match(start,/EXTheme\.set\(e\.target\.value\)/);
assert.match(start,/return; \/\/ Apariencia global, no modifica el examen ni la vista previa/);
assert.match(css,/:root\[data-theme="dark"\], :root\[data-theme="oled"\]/);
assert.match(css,/:root\[data-theme="oled"\] \{/);
assert.match(css,/--preview-bg: #000;/);
assert.match(css,/--paper: #000;/);
assert.match(css,/--panel: #000;/);
assert.match(css,/#preview \{[^}]*background: var\(--preview-bg\)/);
assert.match(css,/\.sheet \{[^}]*background: #fff; color: #111;/);
assert.match(css,/\.hbtn\.primary \{[^}]*background: var\(--accent-button\)/);
assert.doesNotMatch(read('js/render.js'),/data-theme|EXTheme/,'La impresión y Word no deben usar el tema del editor');
assert.doesNotMatch(read('js/pdf-export.js'),/data-theme|EXTheme/);

const store=new Map();
const meta={content:'#1d5466',setAttribute(k,v){this[k]=v}};
const rootElement={dataset:{}};
const localStorage={getItem:(k)=>store.get(k)??null,setItem:(k,v)=>store.set(k,v)};
const ctx={document:{documentElement:rootElement,querySelector:()=>meta},window:{},localStorage,console};
vm.createContext(ctx);
vm.runInContext(read('js/theme.js'),ctx);
assert.equal(ctx.window.EXTheme.current(),'light');
assert.equal(rootElement.dataset.theme,'light');
assert.equal(ctx.window.EXTheme.set('dark'),'dark');
assert.equal(rootElement.dataset.theme,'dark');
assert.equal(meta.content,'#121619');
assert.equal(JSON.parse(store.get('examinator.theme')),'dark');
assert.equal(ctx.window.EXTheme.set('oled'),'oled');
assert.equal(rootElement.dataset.theme,'oled');
assert.equal(meta.content,'#000000');
assert.equal(JSON.parse(store.get('examinator.theme')),'oled');
const reload={document:{documentElement:{dataset:{}},querySelector:()=>meta},window:{},localStorage,console};
vm.createContext(reload);vm.runInContext(read('js/theme.js'),reload);
assert.equal(reload.window.EXTheme.current(),'oled','La preferencia sobrevive a la recarga');
assert.equal(reload.document.documentElement.dataset.theme,'oled');
assert.equal(reload.window.EXTheme.set('inexistente'),'light');
assert.equal(reload.document.documentElement.dataset.theme,'light');
assert.equal(meta.content,'#1d5466');

store.set('examinator.theme','{malformed');
const corrupt={document:{documentElement:{dataset:{}},querySelector:()=>meta},window:{},localStorage,console};
vm.createContext(corrupt);vm.runInContext(read('js/theme.js'),corrupt);
assert.equal(corrupt.window.EXTheme.current(),'light','La preferencia corrupta no rompe el arranque');
console.log('OK: claro, oscuro, OLED, persistencia, preferencia corrupta, A4 blanca y botones originales.');
